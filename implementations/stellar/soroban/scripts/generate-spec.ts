import { readFile, mkdir, writeFile } from "node:fs/promises";
import { contract } from "@stellar/stellar-sdk";
import { format } from "prettier";

// The contract specs, read from the WASM that `stellar contract build` writes. The client
// uses them to encode arguments and decode results, so they always match the contracts.
// With --check, fail if the committed file differs from the build.
const check = process.argv.includes("--check");
const entries = async (name: string) =>
  contract.Spec.fromWasm(
    await readFile(`target/wasm32v1-none/release/${name}.wasm`),
  ).entries.map((entry) => entry.toXDR("base64"));
const list = (values: string[]) =>
  `[\n${values.map((value) => `  "${value}",`).join("\n")}\n]`;
const source = await format(
  `// Generated by npm run contracts:build from the contract WASM. Do not edit.
import { contract } from "@stellar/stellar-sdk";

export const paymvcSpec = new contract.Spec(${list(await entries("paymvc"))});

export const creditsSpec = new contract.Spec(${list(await entries("demo_credits"))});
`,
  { parser: "typescript" },
);
const path = "src/chain/generated/specs.ts";
await mkdir("src/chain/generated", { recursive: true });
if (!check) await writeFile(path, source);
else if ((await readFile(path, "utf8").catch(() => "")) !== source)
  throw new Error(`${path} is out of date. Run npm run contracts:build.`);
