import { readFile, mkdir, writeFile } from "node:fs/promises";

// With --check, fail if the committed ABIs differ from the contract build.
const check = process.argv.includes("--check");
await mkdir("src/chain/generated", { recursive: true });
for (const [contract, name] of [
  ["PayMVC", "paymvcAbi"],
  ["DemoCredits", "creditsAbi"],
]) {
  const artifact = JSON.parse(
    await readFile(`out/${contract}.sol/${contract}.json`, "utf8"),
  );
  const path = `src/chain/generated/${name}.ts`;
  const source = `// Generated by npm run contracts:build. Do not edit.\nexport const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  if (!check) await writeFile(path, source);
  else if ((await readFile(path, "utf8").catch(() => "")) !== source)
    throw new Error(`${path} is out of date. Run npm run contracts:build.`);
}
